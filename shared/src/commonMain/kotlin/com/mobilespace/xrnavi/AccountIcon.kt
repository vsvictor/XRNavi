@Composable
internal fun AccountIcon(
    icon: AccountIcon,
    modifier: Modifier = Modifier,
    tint: Color? = null,
    contentDescription: String? = null
) {
    val dark = MaterialTheme.colorScheme.background.red < 0.5f
    val color = tint ?: when (icon.tone) {
        AccountIconTone.Strong -> MaterialTheme.colorScheme.onSurface
        AccountIconTone.Muted -> MaterialTheme.colorScheme.onSurfaceVariant
        AccountIconTone.Policy -> accountPolicyColor()
    }
    val path = if (dark) icon.darkPath ?: icon.path else icon.path
    val filled = icon.filled && !(dark && icon.darkPath != null)
    val strokeWidth = if (dark && icon.darkPath != null) icon.darkStrokeWidth else 1f
    val vector = remember(icon, color, dark) {
        val builder = ImageVector.Builder(
            icon.name,
            icon.viewport.dp,
            icon.viewport.dp,
            icon.viewport,
            icon.viewport
        )
        val pathData = PathParser().parsePathString(path).toNodes()
        if (filled) {
            builder.addGroup(
                clipPathData = PathParser().parsePathString(
                    "M12 24C18.6274 24 24 18.6274 24 12C24 5.37258 18.6274 0 12 0C5.37258 0 0 5.37258 0 12C0 18.6274 5.37258 24 12 24Z"
                ).toNodes()
            )
            builder.addPath(
                pathData = pathData,
                pathFillType = PathFillType.NonZero,
                fill = SolidColor(color)
            )
            builder.clearGroup()
        } else {
            builder.addPath(
                pathData = pathData,
                stroke = SolidColor(color),
                strokeLineWidth = strokeWidth,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Miter
            )
        }

        builder.build()
    }
    Icon(
        vector,
        contentDescription = contentDescription,
        modifier = modifier,
        tint = Color.Unspecified
    )
}

